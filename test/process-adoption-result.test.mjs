import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import test from 'node:test';

import { validateProcessAdoptionResult } from '../scripts/validate-process-adoption-result.mjs';

const repository = 'phuongnse/lyric-rail';
const checkpoint = 'a'.repeat(40);
const headSha = 'b'.repeat(40);
const token = 't'.repeat(40);
const consumer = {
  repository,
  defaultBranch: 'main',
  checkpoint,
  configPath: '.github/renovate.json',
  configSha256: `sha256:${'c'.repeat(64)}`,
};

function fileDocument(content) {
  const bytes = Buffer.from(content, 'utf8');
  return {
    type: 'file',
    encoding: 'base64',
    content: bytes.toString('base64'),
    size: bytes.length,
  };
}

function candidate(version, { requirementsDigest } = {}) {
  const source = `--only-binary :all:\n\nengineering-process==${version}\n`;
  const requirements = `#
# This file is autogenerated by pip-compile with Python 3.12
# by the following command:
#
#    pip-compile --generate-hashes --no-emit-index-url --output-file=requirements/process.txt --strip-extras requirements/process.in
#
--only-binary :all:

engineering-process==${version} \\
    --hash=sha256:${'d'.repeat(64)}
`;
  const digest = requirementsDigest
    ?? `sha256:${createHash('sha256').update(requirements).digest('hex')}`;
  const lock = `${JSON.stringify({
    schemaVersion: 2,
    process: {
      package: 'engineering-process',
      version,
      digest: `sha256:${'e'.repeat(64)}`,
    },
    requirementsDigest: digest,
    skills: ['run-change'],
    managedFiles: ['.agents/skills/run-change/SKILL.md'],
  }, null, 2)}\n`;
  return {
    '.process/process.lock': fileDocument(lock),
    'requirements/process.in': fileDocument(source),
    'requirements/process.txt': fileDocument(requirements),
  };
}

function response(document, status = 200) {
  const bytes = Buffer.from(JSON.stringify(document));
  return {
    ok: status >= 200 && status < 300,
    status,
    headers: { get: (name) => name.toLowerCase() === 'content-length' ? String(bytes.length) : null },
    arrayBuffer: async () => bytes,
  };
}

function fetchFixture({
  candidateVersion = '1.1.1',
  draft = true,
  mainVersion = '1.0.1',
  requirementsDigest,
} = {}) {
  const mainFiles = candidate(mainVersion);
  const branchFiles = candidate(candidateVersion, { requirementsDigest });
  return async (rawUrl) => {
    const url = new URL(rawUrl);
    if (url.pathname === `/repos/${repository}/pulls`) {
      return response([{
        state: 'open',
        draft,
        head: { ref: 'automation/renovate/engineering-process', sha: headSha, repo: { full_name: repository } },
        base: { ref: 'main', repo: { full_name: repository } },
      }]);
    }
    const prefix = `/repos/${repository}/contents/`;
    if (url.pathname.startsWith(prefix)) {
      const path = url.pathname.slice(prefix.length);
      const ref = url.searchParams.get('ref');
      const document = ref === checkpoint ? mainFiles[path] : ref === headSha ? branchFiles[path] : null;
      if (document) return response(document);
    }
    throw new Error(`unexpected GitHub API request: ${url.pathname}${url.search}`);
  };
}

test('exact release postcondition accepts one bound draft adoption candidate', async () => {
  const result = await validateProcessAdoptionResult({
    consumer,
    fetchImpl: fetchFixture(),
    releaseVersion: '1.1.1',
    token,
  });
  assert.equal(result.location, 'pull-request');
  assert.equal(result.ref, headSha);
  assert.equal(result.version, '1.1.1');
});

test('exact release postcondition accepts an already adopted main checkpoint', async () => {
  const result = await validateProcessAdoptionResult({
    consumer,
    fetchImpl: fetchFixture({ mainVersion: '1.1.1' }),
    releaseVersion: '1.1.1',
    token,
  });
  assert.equal(result.location, 'main');
  assert.equal(result.ref, checkpoint);
});

test('exact release postcondition rejects a stale successful Renovate candidate', async () => {
  await assert.rejects(
    validateProcessAdoptionResult({
      consumer,
      fetchImpl: fetchFixture({ candidateVersion: '1.1.0' }),
      releaseVersion: '1.1.1',
      token,
    }),
    /process source must pin exact release 1\.1\.1/,
  );
});

test('exact release postcondition requires one draft pull request', async () => {
  await assert.rejects(
    validateProcessAdoptionResult({
      consumer,
      fetchImpl: fetchFixture({ draft: false }),
      releaseVersion: '1.1.1',
      token,
    }),
    /adoption pull request is not one exact open draft/,
  );
});

test('exact release postcondition rejects requirements digest drift', async () => {
  await assert.rejects(
    validateProcessAdoptionResult({
      consumer,
      fetchImpl: fetchFixture({ requirementsDigest: `sha256:${'f'.repeat(64)}` }),
      releaseVersion: '1.1.1',
      token,
    }),
    /requirementsDigest does not bind the candidate bytes/,
  );
});
