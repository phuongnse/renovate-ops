import { createHash } from 'node:crypto';
import { appendFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

import { githubClient } from './discover-consumers.mjs';
import {
  manifestForConsumer,
  MAX_MANIFEST_BYTES,
} from './validate-consumer-manifest.mjs';

const ADOPTION_BRANCH = 'automation/renovate/engineering-process';
const MAX_FILE_BYTES = 2_000_000;
const SEMVER = /^(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)$/;
const SHA = /^[0-9a-f]{40}$/;
const DIGEST = /^sha256:[0-9a-f]{64}$/;
const CANONICAL_COMPILE_COMMAND =
  '#    pip-compile --generate-hashes --no-emit-index-url --output-file=requirements/process.txt --strip-extras requirements/process.in';
const GENERATED_HEADER = /^# This file is autogenerated by pip-compile with Python \d+(?:\.\d+)+$/;
const INDIRECT_REQUIREMENT = /^(?:-[erc]|--(?:constraint|editable|requirement)(?:$|[=\s]))/;
const HASH_LINE = /^ {4}--hash=sha256:[0-9a-f]{64}(?: \\)?$/;
const HASH_CONTINUATION = / \\$/;

export class ReleaseNotObservedError extends Error {}

function isOlderFinalVersion(observed, expected) {
  if (!SEMVER.test(observed) || !SEMVER.test(expected)) return false;
  const left = observed.split('.');
  const right = expected.split('.');
  for (let index = 0; index < left.length; index += 1) {
    if (left[index].length !== right[index].length) {
      return left[index].length < right[index].length;
    }
    if (left[index] !== right[index]) return left[index] < right[index];
  }
  return false;
}

function canonicalName(value) {
  return value.toLowerCase().replaceAll(/[._-]+/g, '-');
}

export function processBinding(content, { compiled, label }) {
  const lines = content.split('\n');
  const bindings = [];
  const canonical = compiled
    ? /^engineering-process==([^\s\\]+) \\$/
    : /^engineering-process==([^\s\\]+)$/;
  for (const [index, raw] of lines.entries()) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    if (INDIRECT_REQUIREMENT.test(line)) {
      throw new Error(`${label} must not use indirect or editable requirements`);
    }
    if (line.startsWith('-')) continue;
    const name = line.match(/^([A-Za-z0-9][A-Za-z0-9._-]*)/)?.[1];
    if (!name || canonicalName(name) !== 'engineering-process') continue;
    const match = canonical.exec(raw);
    if (match === null) {
      throw new Error(`${label} has a non-canonical active engineering-process requirement`);
    }
    bindings.push({ index, version: match[1] });
  }
  if (bindings.length !== 1) {
    throw new Error(`${label} must contain exactly one active engineering-process requirement`);
  }
  return { ...bindings[0], lines };
}

function decodeFile(document, label) {
  if (
    document === null
    || document.type !== 'file'
    || document.encoding !== 'base64'
    || typeof document.content !== 'string'
    || !Number.isInteger(document.size)
    || document.size < 1
    || document.size > MAX_FILE_BYTES
  ) {
    throw new Error(`${label} is not a bounded base64 file`);
  }
  const encoded = document.content.replaceAll('\n', '');
  if (!/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(encoded)) {
    throw new Error(`${label} contains invalid base64`);
  }
  const bytes = Buffer.from(encoded, 'base64');
  if (bytes.toString('base64') !== encoded || bytes.length !== document.size) {
    throw new Error(`${label} base64 size or content is inconsistent`);
  }
  let text;
  try {
    text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
  } catch {
    throw new Error(`${label} must be UTF-8`);
  }
  return { bytes, text };
}

async function fileAt(api, repository, path, ref) {
  const document = await api(
    `/repos/${repository}/contents/${path}?ref=${encodeURIComponent(ref)}`,
  );
  return decodeFile(document, `${repository}/${path}@${ref}`);
}

function parseLock(text, label) {
  let lock;
  try {
    lock = JSON.parse(text);
  } catch {
    throw new Error(`${label} must be strict JSON`);
  }
  if (
    lock === null
    || typeof lock !== 'object'
    || Array.isArray(lock)
    || lock.schemaVersion !== 2
    || lock.process?.package !== 'engineering-process'
    || !SEMVER.test(lock.process?.version)
    || !DIGEST.test(lock.process?.digest)
    || !DIGEST.test(lock.requirementsDigest)
  ) {
    throw new Error(`${label} has an invalid process binding`);
  }
  return lock;
}

export async function validateCandidate(api, repository, ref, releaseVersion) {
  const source = await fileAt(api, repository, 'requirements/process.in', ref);
  const requirements = await fileAt(api, repository, 'requirements/process.txt', ref);
  const lockFile = await fileAt(api, repository, '.process/process.lock', ref);
  const sourceBinding = processBinding(source.text, {
    compiled: false,
    label: `${repository}/requirements/process.in@${ref}`,
  });
  const requirementsBinding = processBinding(requirements.text, {
    compiled: true,
    label: `${repository}/requirements/process.txt@${ref}`,
  });
  if (requirementsBinding.version !== sourceBinding.version) {
    throw new Error(`${repository} process requirements must match the source version`);
  }
  const recordedCommands = requirementsBinding.lines.filter((line) => /^# {4}\S/.test(line));
  if (
    JSON.stringify(recordedCommands) !== JSON.stringify([CANONICAL_COMPILE_COMMAND])
    || requirementsBinding.lines[0] !== '#'
    || !GENERATED_HEADER.test(requirementsBinding.lines[1] ?? '')
    || requirementsBinding.lines[2] !== '# by the following command:'
    || requirementsBinding.lines[3] !== '#'
    || requirementsBinding.lines[4] !== CANONICAL_COMPILE_COMMAND
    || requirementsBinding.lines[5] !== '#'
    || requirementsBinding.lines[6] !== '--only-binary :all:'
  ) {
    throw new Error(`${repository} process requirements header is not canonical`);
  }
  const hashLines = [];
  for (const line of requirementsBinding.lines.slice(requirementsBinding.index + 1)) {
    if (!line.startsWith('    --hash=')) break;
    hashLines.push(line);
  }
  if (
    hashLines.length < 1
    || hashLines.some((line) => !HASH_LINE.test(line))
    || hashLines.slice(0, -1).some((line) => !HASH_CONTINUATION.test(line))
    || HASH_CONTINUATION.test(hashLines.at(-1))
  ) {
    throw new Error(`${repository} process requirement is not hash locked`);
  }
  const lock = parseLock(lockFile.text, `${repository}/.process/process.lock@${ref}`);
  if (lock.process.version !== sourceBinding.version) {
    throw new Error(`${repository} process lock must match the source version`);
  }
  const requirementsDigest = `sha256:${createHash('sha256').update(requirements.bytes).digest('hex')}`;
  if (lock.requirementsDigest !== requirementsDigest) {
    throw new Error(`${repository} requirementsDigest does not bind the candidate bytes`);
  }
  if (sourceBinding.version !== releaseVersion) {
    const message = `${repository} process source must pin exact release ${releaseVersion}`;
    if (isOlderFinalVersion(sourceBinding.version, releaseVersion)) {
      throw new ReleaseNotObservedError(message);
    }
    throw new Error(message);
  }
  return { ref, repository, version: releaseVersion };
}

function validatePullRequest(pull, consumer) {
  if (
    pull === null
    || typeof pull !== 'object'
    || pull.draft !== true
    || pull.state !== 'open'
    || pull.head?.ref !== ADOPTION_BRANCH
    || !SHA.test(pull.head?.sha)
    || pull.head?.repo?.full_name !== consumer.repository
    || pull.base?.ref !== consumer.defaultBranch
    || pull.base?.sha !== consumer.checkpoint
    || pull.base?.repo?.full_name !== consumer.repository
  ) {
    throw new Error(`${consumer.repository} adoption pull request is not one exact open draft`);
  }
  return pull.head.sha;
}

export async function validateProcessAdoptionResult({
  consumer,
  fetchImpl = fetch,
  releaseVersion,
  token,
}) {
  const expected = manifestForConsumer(consumer).consumers[0];
  if (!SEMVER.test(releaseVersion)) throw new Error('release version must be final SemVer');
  const api = githubClient(token, fetchImpl);
  const mainSource = await fileAt(
    api,
    expected.repository,
    'requirements/process.in',
    expected.checkpoint,
  );
  const mainBinding = processBinding(mainSource.text, {
    compiled: false,
    label: `${expected.repository}/requirements/process.in@${expected.checkpoint}`,
  });
  if (!SEMVER.test(mainBinding.version)) {
    throw new Error(`${expected.repository} main process source must pin final SemVer`);
  }
  if (mainBinding.version === releaseVersion) {
    return {
      ...(await validateCandidate(api, expected.repository, expected.checkpoint, releaseVersion)),
      location: 'main',
    };
  }
  if (isOlderFinalVersion(releaseVersion, mainBinding.version)) {
    throw new Error(
      `${expected.repository} main process source is newer than release ${releaseVersion}`,
    );
  }
  const head = encodeURIComponent(`phuongnse:${ADOPTION_BRANCH}`);
  const base = encodeURIComponent(expected.defaultBranch);
  const pulls = await api(
    `/repos/${expected.repository}/pulls?state=open&head=${head}&base=${base}&per_page=10`,
  );
  if (!Array.isArray(pulls) || pulls.length !== 1) {
    throw new Error(`${expected.repository} must have one open process adoption pull request`);
  }
  const headSha = validatePullRequest(pulls[0], expected);
  return {
    ...(await validateCandidate(api, expected.repository, headSha, releaseVersion)),
    location: 'pull-request',
  };
}

export async function classifyProcessAdoptionResult(options) {
  try {
    return {
      classification: 'complete',
      result: await validateProcessAdoptionResult(options),
      status: 'passed',
    };
  } catch (error) {
    if (!(error instanceof ReleaseNotObservedError)) throw error;
    return {
      classification: 'release-not-observed',
      message: error.message,
      status: 'retryable',
    };
  }
}

async function main() {
  const classify = process.argv.length === 3 && process.argv[2] === '--classify';
  if (process.argv.length !== (classify ? 3 : 2)) {
    throw new Error('usage: validate-process-adoption-result.mjs [--classify]');
  }
  const encoded = process.env.RENOVATE_CONSUMER_JSON;
  if (typeof encoded !== 'string' || Buffer.byteLength(encoded) > MAX_MANIFEST_BYTES) {
    throw new Error('RENOVATE_CONSUMER_JSON must be a bounded string');
  }
  let consumer;
  try {
    consumer = JSON.parse(encoded);
  } catch {
    throw new Error('RENOVATE_CONSUMER_JSON must be valid JSON');
  }
  const options = {
    consumer,
    releaseVersion: process.env.RELEASE_VERSION,
    token: process.env.GH_TOKEN,
  };
  const result = classify
    ? await classifyProcessAdoptionResult(options)
    : { ...(await validateProcessAdoptionResult(options)), status: 'passed' };
  if (classify) {
    const output = process.env.GITHUB_OUTPUT;
    if (!output) throw new Error('GITHUB_OUTPUT is required');
    await appendFile(
      output,
      `status=${result.status}\nclassification=${result.classification}\n`,
      'utf8',
    );
  }
  process.stdout.write(`${JSON.stringify(result)}\n`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    process.stderr.write(`process adoption result validation failed: ${error.message}\n`);
    process.exitCode = 1;
  });
}
